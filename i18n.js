  let language = localStorage.getItem(STORAGE_KEY) === "fa" ? "fa" : "en";
  const sourceText = new WeakMap();
  const renderedText = new WeakMap();
  const sourceAttributes = new WeakMap();
  const renderedAttributes = new WeakMap();
  let observer = null;

  function translateCore(value) {
    if (language !== "fa" || value == null) return String(value ?? "");
    const text = String(value);
    if (Object.prototype.hasOwnProperty.call(FA, text)) return FA[text];
    for (const [regex, replacer] of patterns) {
      const match = text.match(regex);
      if (match) return replacer(match);
    }
    if (text.includes(" · ")) {
      const parts = text.split(" · "), translated = parts.map(part => translateCore(part));
      if (translated.some((part,index) => part !== parts[index])) return translated.join(" · ");
    }
    return text;
  }

  function translate(value) {
    if (value == null || language !== "fa") return String(value ?? "");
    const text = String(value);
    const match = text.match(/^(\s*)([\s\S]*?)(\s*)$/);
    return `${match[1]}${translateCore(match[2])}${match[3]}`;
  }

  function shouldSkipText(node) {
    const parent = node.parentElement;
    if (!parent || parent.closest("script,style,template,[data-i18n='off'],.chat-body,.sheet-summary,.tag-chip,.scene-title-stack small,.project-open-area h3,.admin-project-row strong,#accountDisplayName,#accountIdentityName,#accountAvatarInitial,#accountUsername,#accountEmail,#mobileEditorTitle")) return true;
    return false;
  }

  function applyTextNode(node, acceptNewSource = false) {
    if (!node || shouldSkipText(node) || !node.nodeValue || !node.nodeValue.trim()) return;
    const parent = node.parentElement;
    if (parent?.tagName === "OPTION" && !parent.hasAttribute("value")) parent.setAttribute("value", parent.value);
    if (acceptNewSource || !sourceText.has(node)) sourceText.set(node, node.nodeValue);
    const output = language === "fa" ? translate(sourceText.get(node)) : sourceText.get(node);
    renderedText.set(node, output);
    if (node.nodeValue !== output) node.nodeValue = output;
  }

  function attributeMap(store, element) {
    let map = store.get(element);
    if (!map) { map = new Map(); store.set(element, map); }
    return map;
  }

  function applyAttribute(element, name, acceptNewSource = false) {
    if (!element?.hasAttribute?.(name) || element.closest?.("[data-i18n='off']")) return;
    const sources = attributeMap(sourceAttributes, element);
    const rendered = attributeMap(renderedAttributes, element);
    if (acceptNewSource || !sources.has(name)) sources.set(name, element.getAttribute(name));
    const output = language === "fa" ? translate(sources.get(name)) : sources.get(name);
    rendered.set(name, output);
    if (element.getAttribute(name) !== output) element.setAttribute(name, output);
  }

  function translateTree(root = document) {
    if (!root) return;
    if (root.nodeType === Node.TEXT_NODE) applyTextNode(root);
    else {
      if (root.nodeType === Node.ELEMENT_NODE) ATTRIBUTE_NAMES.forEach(name => applyAttribute(root, name));
      const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
      let node;
      while ((node = walker.nextNode())) applyTextNode(node);
      const elements = root.querySelectorAll?.(ATTRIBUTE_NAMES.map(name => `[${name}]`).join(",")) || [];
      elements.forEach(element => ATTRIBUTE_NAMES.forEach(name => applyAttribute(element, name)));
    }
  }

  function updateToggle() {
    const button = document.getElementById("languageToggleBtn");
    const label = document.getElementById("languageToggleLabel");
    if (!button || !label) return;
    label.textContent = language === "fa" ? "English" : "فارسی";
    button.setAttribute("aria-label", language === "fa" ? "تغییر زبان به انگلیسی" : "Switch language to Persian");
    button.title = language === "fa" ? "English" : "فارسی";
  }

  function setLanguage(next, announce = true) {
    language = next === "fa" ? "fa" : "en";
    localStorage.setItem(STORAGE_KEY, language);
    document.documentElement.lang = language;
    document.documentElement.dir = language === "fa" ? "rtl" : "ltr";
    document.title = language === "fa" ? "سازنده شات‌های استوری‌بورد" : "Storyboard Shot Builder";
    translateTree(document.body);
    updateToggle();
    if (announce) window.dispatchEvent(new CustomEvent("storyboard:languagechange", {detail:{language}}));
  }

  function observe() {
    observer = new MutationObserver(mutations => {
      for (const mutation of mutations) {
        if (mutation.type === "characterData") {
          if (renderedText.get(mutation.target) === mutation.target.nodeValue) continue;
          applyTextNode(mutation.target, true);
        } else if (mutation.type === "attributes") {
          const rendered = renderedAttributes.get(mutation.target)?.get(mutation.attributeName);
          if (rendered === mutation.target.getAttribute(mutation.attributeName)) continue;
          applyAttribute(mutation.target, mutation.attributeName, true);
        } else {
          mutation.addedNodes.forEach(node => translateTree(node));
        }
      }
    });
    observer.observe(document.body, {subtree:true, childList:true, characterData:true, attributes:true, attributeFilter:ATTRIBUTE_NAMES});
  }

